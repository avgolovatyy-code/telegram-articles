def _fold(value: str) -> str:
    return re.sub(r"[^a-zа-яё0-9]+", " ", value.casefold()).strip()


def normalize_destination_country(value: str | None) -> str | None:
    """Return an ISO alpha-2 code, or a varchar(16)-safe fallback, or None."""
    if value is None:
        return None
    raw = str(value).strip()
    if not raw:
        return None
    letters = re.sub(r"[^A-Za-z]", "", raw)
    if len(letters) == 2 and letters.isalpha():
        return letters.upper()
    if len(letters) == 3:
        mapped3 = _ISO3_TO_ISO2.get(letters.upper())
        if mapped3:
            return mapped3
    mapped = _NAME_TO_ISO.get(_fold(raw))
    if mapped:
        return mapped
    return raw[:COUNTRY_CODE_MAX_LEN]


